"""
Packs the website in ../web into smart_ac_controller/web_files.h
(gzip-compressed byte arrays stored in flash), so the Arduino sketch can serve it
without a separate LittleFS upload.

Run this again after ANY change in the web/ folder:
    python build_web_header.py
"""
import gzip
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.join(HERE, '..', 'web')
OUT = os.path.join(HERE, 'smart_ac_controller', 'web_files.h')

TYPES = {
    '.html': 'text/html; charset=utf-8',
    '.css': 'text/css; charset=utf-8',
    '.js': 'application/javascript; charset=utf-8',
    '.json': 'application/json',
    '.svg': 'image/svg+xml',
    '.png': 'image/png',
    '.ico': 'image/x-icon',
}


def collect():
    files = []
    for root, _dirs, names in os.walk(WEB):
        for n in names:
            ext = os.path.splitext(n)[1].lower()
            if ext not in TYPES:      # skips README.md, TESTING.md, etc.
                continue
            full = os.path.join(root, n)
            rel = '/' + os.path.relpath(full, WEB).replace('\\', '/')
            files.append((rel, full, TYPES[ext]))
    return sorted(files)


def main():
    files = collect()
    out = ['// AUTO-GENERATED by build_web_header.py — do not edit by hand.',
           '#pragma once',
           '#include <Arduino.h>', '',
           'struct WebFile { const char* path; const char* type; const uint8_t* data; size_t len; };', '']
    total = 0
    for i, (rel, full, _t) in enumerate(files):
        raw = open(full, 'rb').read()
        gz = gzip.compress(raw, 9, mtime=0)
        total += len(gz)
        out.append('// %s  (%d bytes -> %d gzipped)' % (rel, len(raw), len(gz)))
        out.append('const uint8_t web_file_%d[] PROGMEM = {' % i)
        for j in range(0, len(gz), 20):
            out.append('  ' + ','.join('0x%02x' % b for b in gz[j:j + 20]) + ',')
        out.append('};')
        out.append('')
    out.append('const WebFile WEB_FILES[] = {')
    for i, (rel, full, t) in enumerate(files):
        gz_len = len(gzip.compress(open(full, 'rb').read(), 9, mtime=0))
        out.append('  { "%s", "%s", web_file_%d, %d },' % (rel, t, i, gz_len))
    out.append('};')
    out.append('const size_t WEB_FILE_COUNT = %d;' % len(files))
    open(OUT, 'w', newline='\n').write('\n'.join(out) + '\n')
    print('Wrote %s: %d files, %d bytes gzipped' % (os.path.normpath(OUT), len(files), total))
    for rel, _f, _t in files:
        print('  ', rel)


if __name__ == '__main__':
    main()
